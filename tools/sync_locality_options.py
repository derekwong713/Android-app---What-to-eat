"""Regenerate display membership from classified bundled restaurants, preserving stable locality IDs."""
import json
from pathlib import Path

def sync(rows,config=Path('tools/hk-localities.json'),output=Path('app/src/main/java/hk/whatoeat/core/model/LocalityOptions.kt')):
    areas=json.loads(config.read_text(encoding='utf-8'))
    for key,item in areas.items():
        observed=sorted({r['region'] for r in rows if r.get('locality')==key and r['region']!='unknown'})
        item['districts']=observed or item.get('districts',[])
    config.write_text(json.dumps(areas,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    code='''package hk.whatoeat.core.model

/** Generated by tools/sync_locality_options.py from source localities and classified coordinates. */
object LocalityOptions {
    val labels=linkedMapOf(
'''+',\n'.join(f'        "{key}" to "{item["label"]}"' for key,item in areas.items())+'''
    )
    val memberships=mapOf(
'''+',\n'.join('        "'+key+'" to '+('setOf('+','.join('"'+d+'"' for d in item['districts'])+')' if item['districts'] else 'emptySet<String>()') for key,item in areas.items())+'''
    )
    fun covered(id: String,selection: Set<String>): Boolean = memberships[id]?.let {it.isNotEmpty() && selection.containsAll(it)}==true
    fun displayLabel(id: String): String = labels.getValue(id)+(if(memberships[id].orEmpty().size>1) "（多區資料）" else "")
}
'''
    output.write_text(code,encoding='utf-8')
if __name__=='__main__':sync(json.loads(Path('app/src/main/assets/restaurants.json').read_text(encoding='utf-8')))
